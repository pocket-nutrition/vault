"""Generate docs/test-vectors.json: known answers for the vault's crypto, from libsodium via PyNaCl.

Every client (iOS, Android, any external reader) must reproduce these byte for byte. Run with a Python
that has PyNaCl: `python scripts/gen_vectors.py > docs/test-vectors.json`. The output is deterministic
except for the sealed box (random by design), which is fixed once and committed.
"""

import base64
import hashlib
import json
import sys

from nacl import bindings, pwhash
from nacl.public import PrivateKey, SealedBox

b64 = lambda raw: base64.b64encode(raw).decode()  # noqa: E731
hexs = lambda raw: raw.hex()  # noqa: E731


def kdf_subkey(master: bytes, subkey_id: int, context: bytes) -> bytes:
    """libsodium's crypto_kdf_derive_from_key, which PyNaCl does not expose.

    Defined by libsodium as keyed BLAKE2b with salt = LE64(subkey_id) padded to 16 bytes and
    personalization = the 8-byte context padded to 16. Clients use the real function; their tests
    reproducing this output is what proves this emulation right.
    """
    assert len(context) == 8 and len(master) == 32
    salt = subkey_id.to_bytes(8, "little") + bytes(8)
    return hashlib.blake2b(b"", digest_size=32, key=master, salt=salt, person=context + bytes(8)).digest()


def main() -> None:
    passphrase = b"correct horse battery staple"
    salt = bytes(range(16))
    ops, mem = 3, 64 * 1024 * 1024
    master = pwhash.argon2id.kdf(32, passphrase, salt, opslimit=ops, memlimit=mem)
    auth_hash = kdf_subkey(master, 1, b"pnvauth1")
    wrap_key = kdf_subkey(master, 2, b"pnvwrap1")

    aead_key = bytes(range(100, 132))
    aead_nonce = bytes(range(200, 224))
    aead_plaintext = b'{"kind":"meal","kcal":520}'
    aad = b"pnv1|acc-1|rec-1|capture||3|user"
    aead_ct = bindings.crypto_aead_xchacha20poly1305_ietf_encrypt(aead_plaintext, aad, aead_nonce, aead_key)

    inbox_private = bytes(range(32, 64))
    inbox = PrivateKey(inbox_private)
    sealed_plaintext = (
        b'{"v":1,"record_id":"cap-1","ticket_id":"t-1","status":"done",'
        b'"result":{"transcript":"deux oeufs","language":"fr","items":[]},"error":null}'
    )
    sealed = SealedBox(inbox.public_key).encrypt(sealed_plaintext)

    json.dump(
        {
            "about": "Known answers for the Pocket Nutrition Vault protocol. Generated by scripts/gen_vectors.py.",
            "kdf": {
                "passphrase_utf8": passphrase.decode(),
                "salt_hex": hexs(salt),
                "opslimit": ops,
                "memlimit": mem,
                "master_key_hex": hexs(master),
                "auth_hash_hex": hexs(auth_hash),
                "auth_hash_b64": b64(auth_hash),
                "wrap_key_hex": hexs(wrap_key),
            },
            "record_aead": {
                "key_hex": hexs(aead_key),
                "nonce_hex": hexs(aead_nonce),
                "aad_utf8": aad.decode(),
                "plaintext_utf8": aead_plaintext.decode(),
                "ciphertext_b64": b64(aead_nonce + aead_ct),
            },
            "sealed_box": {
                "inbox_private_key_hex": hexs(inbox_private),
                "inbox_public_key_hex": hexs(bytes(inbox.public_key)),
                "plaintext_utf8": sealed_plaintext.decode(),
                "sealed_b64": b64(sealed),
            },
        },
        sys.stdout,
        indent=2,
    )
    print()


if __name__ == "__main__":
    main()
